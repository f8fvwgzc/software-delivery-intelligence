import type { components } from '@/lib/api/schema'
import { count } from '@/lib/intl'

import type { DeliveryArtifacts } from '../api/types'

type CreateExecutionRequest = components['schemas']['CreateExecutionRequest']
type Project = components['schemas']['Project']

const TITLE = 'Add continuous delivery setup'

function pullRequestBody({ artifacts, notes, requiredSecrets }: DeliveryArtifacts) {
  const lines = ['## Continuous delivery setup', '', 'Build, release and deploy files for the environments of this project.', '', '### Files', '']
  for (const file of artifacts) {
    lines.push(`- \`${file.path}\`${file.replacesExisting ? ' (replaces the existing file)' : ''}: ${file.purpose}`)
  }
  if (notes.length > 0) {
    lines.push('', '### Before merging', '')
    for (const note of notes) lines.push(`- ${note}`)
  }
  if (requiredSecrets.length > 0) {
    lines.push('', '### Secrets these files reference', '')
    for (const name of requiredSecrets) lines.push(`- \`${name}\``)
  }
  lines.push('', 'Generated by Software Delivery Intelligence from the repository’s own facts.')
  return lines.join('\n')
}

/**
 * The plan that offers the setup files as a pull request: the same two
 * steps the proposals feature runs (checkout, then `repo.open_pull_request`
 * through the `github` adapter), with the files in `artifacts`. The branch
 * is left to the adapter, which names it after the execution, so asking
 * twice never pushes onto an earlier branch.
 */
export function setupPullRequest(project: Pick<Project, 'id' | 'repoFullName' | 'defaultBranch'>, files: DeliveryArtifacts): CreateExecutionRequest {
  const branch = project.defaultBranch || 'main'
  const repository = { repository: project.repoFullName, branch }

  return {
    projectId: project.id,
    title: TITLE,
    adapter: 'github',
    artifacts: Object.fromEntries(files.artifacts.map((file) => [file.path, file.content])),
    steps: [
      {
        key: 'checkout',
        title: 'Download the repository at the default branch',
        description: '',
        actionType: 'repo.checkout',
        adapter: 'github',
        dependsOn: [],
        requiredPermissions: ['repository:read'],
        params: repository,
        verification: 'the default branch head is known',
      },
      {
        key: 'pull_request',
        title: `Open a pull request with ${count(files.artifacts.length, 'setup file', 'setup files')}`,
        description: '',
        actionType: 'repo.open_pull_request',
        adapter: 'github',
        dependsOn: ['checkout'],
        requiredPermissions: ['repository:write'],
        params: { repository: project.repoFullName, base_branch: branch, title: TITLE, body: pullRequestBody(files) },
        verification: 'the pull request exists and lists every generated file',
      },
    ],
  }
}
